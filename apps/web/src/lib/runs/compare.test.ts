import { parseRunEvent, type RunEvent } from "@delegate/runtime";
import { describe, expect, it } from "vitest";

import { simulatedScript } from "@/server/fake-runner";
import type { EventDraft } from "@/server/runs";

import { compareRuns } from "./compare";
import { forkInfo } from "./fork";

const homepage = "https://acme.com/";

function created(runId: string, forkedFrom?: Record<string, unknown>): Record<string, unknown> {
  return {
    type: "run.created",
    payload: {
      workspaceId: "ws",
      missionId: "company-xray",
      input: { url: homepage, execution: "simulated" },
      actor: { type: "guest", id: "g" },
      budget: { maxTokens: 1, maxMicroUsd: 0 },
      ...(forkedFrom === undefined ? {} : { forkedFrom }),
    },
  };
}

function toLog(runId: string, drafts: readonly unknown[], stepMs = 1000): RunEvent[] {
  const start = Date.parse("2026-11-25T10:00:00.000Z");
  return drafts.map((draft, index) =>
    parseRunEvent({
      runId,
      seq: index + 1,
      at: new Date(start + index * stepMs).toISOString(),
      ...(draft as Record<string, unknown>),
    }),
  );
}

function rewriteClaims(drafts: EventDraft[]): EventDraft[] {
  return drafts.map((draft) => {
    if (draft.type !== "artifact.updated") return draft;
    const payload = draft.payload as { content: { sections: Record<string, unknown> } };
    const sections = {
      ...payload.content.sections,
      offering: {
        status: "ok",
        claims: [
          {
            text: "Simulated claim: this text was generated by the dev fake runner, not by real research.",
            citations: ["S1"],
          },
          { text: "A brand new claim about pricing tiers.", citations: ["S2"] },
        ],
      },
    };
    return { ...draft, payload: { ...payload, content: { ...payload.content, sections } } };
  });
}

describe("compareRuns", () => {
  const a = toLog("run-a", [created("run-a"), ...simulatedScript("run-a", homepage)]);
  const b = toLog(
    "run-b",
    [created("run-b"), ...rewriteClaims(simulatedScript("run-b", homepage))],
    500,
  );

  it("puts the headline metrics of both runs side by side", () => {
    const result = compareRuns({ runId: "run-a", events: a }, { runId: "run-b", events: b });
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.sameMission).toBe(true);
    expect(result.a).toMatchObject({
      runId: "run-a",
      execution: "simulated",
      outcome: "completed",
      stepsDone: 3,
      stepsTotal: 3,
      inputTokens: 7400,
      outputTokens: 1750,
      sources: 2,
      fork: null,
    });
    expect([...result.a.models].sort()).toEqual([
      "simulated-fast-backup",
      "simulated-planner",
      "simulated-worker",
    ]);
    expect(result.a.durationMs).toBe((a.length - 1) * 1000);
    expect(result.b.durationMs).toBe((b.length - 1) * 500);
  });

  it("diffs the briefs claim by claim", () => {
    const result = compareRuns({ runId: "run-a", events: a }, { runId: "run-b", events: b });
    if (!result.ok) throw new Error(result.error);
    const kinds = (result.claims ?? []).map((change) => `${change.section}:${change.kind}`);
    expect(kinds).toContain("Offering:changed");
    expect(kinds).toContain("Offering:added");
    expect(kinds.filter((kind) => kind.endsWith(":unchanged")).length).toBeGreaterThan(0);
  });

  it("reports an unreadable log instead of throwing", () => {
    const result = compareRuns({ runId: "x", events: a.slice(1) }, { runId: "run-b", events: b });
    expect(result).toMatchObject({ ok: false });
  });
});

describe("forkInfo", () => {
  it("derives time to first new event, reused and re-run steps from the log", () => {
    const script = simulatedScript("run-f", homepage);
    const cut = script.findIndex((d) => d.type === "step.started" && d.stepId === "read-pages");
    const origin = {
      runId: "run-a",
      stepId: "read-pages",
      parentSeq: cut + 1,
      seededThrough: cut + 1,
      objectiveEdited: false,
    };
    const seeded = toLog("run-f", [created("run-f", origin), ...script.slice(0, cut)], 0);
    const fresh = script.slice(cut).map((draft, index) =>
      parseRunEvent({
        runId: "run-f",
        seq: cut + 2 + index,
        at: new Date(Date.parse("2026-11-25T10:00:00.000Z") + 1500 + index).toISOString(),
        ...draft,
      }),
    );
    const info = forkInfo([...seeded, ...fresh]);
    expect(info).toEqual({
      parentRunId: "run-a",
      stepId: "read-pages",
      objectiveEdited: false,
      seededEvents: cut,
      firstNewEventMs: 1500,
      reusedSteps: ["map-site"],
      rerunSteps: ["read-pages", "write-brief"],
    });
    expect(forkInfo(seeded)?.firstNewEventMs).toBeNull();
    expect(forkInfo(toLog("x", [created("x")]))).toBeNull();
  });
});
